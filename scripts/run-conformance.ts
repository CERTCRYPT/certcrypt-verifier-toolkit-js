/**
 * Conformance harness for CERTCRYPT verifier-toolkit.
 *
 * Runs all fixtures under fixtures/conformance/ and fixtures/adversarial/,
 * verifies each against its expected-result.json.
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { join, dirname, isAbsolute, resolve } from "node:path";
import "../core/input/register-node-fs.js"; // side-effect: install the Node fs bridge so *_path artifacts load
import { verify } from "../core/verify.js";
import { getConformanceConfig } from "../harness/profiles.js";
import { initMlDsa65 } from "../core/crypto/ml-dsa.js";
import type { VerifierRequest } from "../core/types/index.js";

// Initialize the ML-DSA-65 backend so fixtures exercising real PQC signatures
// (zero-data capacity Level-1 anchor, proof signatures) verify rather than
// report "unsupported_runtime". No-op if the optional backend is absent.
const mlDsaReady = await initMlDsa65();
if (!mlDsaReady) {
  console.warn(
    "  (warning) ML-DSA-65 backend unavailable: the post-quantum component of " +
      "every composite signature cannot be verified, so the fixtures asserting " +
      "it will FAIL and no attestation will be recorded. Install " +
      "@noble/post-quantum.",
  );
}

// Conformance config: `rules/conformance`, synthetic root. The fixtures carry the
// environment-agnostic contract rules_version, so this is the config that accepts
// them regardless of the verifier's operational environment. Every signature in
// every fixture is verified: there is no mode that accepts one unverified.
const conformanceConfig = getConformanceConfig();

// The authoritative conformance contract lives in the `certcrypt-conformance`
// repository (data-only, versioned), NOT in this toolkit. Its fixtures are
// produced by the canonical generator at certcrypt-conformance/generator/
// (Python). Resolve the fixtures from there so the harness validates against
// the real contract.
//
// Resolution order:
//   1. CERTCRYPT_CONFORMANCE_DIR env var (explicit, for CI), pointing at the
//      `fixtures/` dir of a checked-out certcrypt-conformance.
//   2. The sibling repo at <workspace>/certcrypt-conformance/fixtures (the
//      standard side-by-side checkout convention).
const scriptDir = dirname(new URL(import.meta.url).pathname);
const TOOLKIT_ROOT = join(scriptDir, "..", "..");

function resolveFixturesBase(): string {
  const envDir = process.env.CERTCRYPT_CONFORMANCE_DIR;
  if (envDir && existsSync(envDir)) return envDir;
  // dist/scripts -> dist -> toolkit root -> workspace -> certcrypt-conformance
  const sibling = join(TOOLKIT_ROOT, "..", "certcrypt-conformance", "fixtures");
  // Both directories, not just `conformance/`: a base that resolves on the positive
  // vectors alone would pass the check here and lose the adversarial half below.
  if (
    existsSync(join(sibling, "conformance")) &&
    existsSync(join(sibling, "adversarial"))
  )
    return sibling;
  throw new Error(
    "conformance fixtures not found: set CERTCRYPT_CONFORMANCE_DIR to the " +
      "certcrypt-conformance/fixtures dir, or check out certcrypt-conformance " +
      "as a sibling of this repo. The fixtures are generated by " +
      "certcrypt-conformance/generator/ (Python) and are not vendored here.",
  );
}

const FIXTURES_BASE = resolveFixturesBase();
const FIXTURE_DIRS = [
  join(FIXTURES_BASE, "conformance"),
  join(FIXTURES_BASE, "adversarial"),
];

/**
 * The conformance contract version, read from the `VERSION` of the SAME checkout
 * whose fixtures we are about to run — `FIXTURES_BASE/..`, never a separately
 * resolved path. Reading it from anywhere else would let the recorded version
 * describe a different vector set than the one that actually executed, which is
 * the exact dishonesty this attestation exists to rule out.
 *
 * Fail-closed: an absent, unreadable, or empty `VERSION` aborts the run. A vector
 * set that cannot say which contract it is cannot be attested to, and continuing
 * would produce a green suite with no publishable version — inviting a hand-written
 * one to fill the gap.
 */
function readVectorsVersion(): string {
  const versionPath = join(FIXTURES_BASE, "..", "VERSION");
  if (!existsSync(versionPath)) {
    throw new Error(
      `conformance vectors present but VERSION is missing at ${versionPath}: ` +
        "the vector set cannot identify which contract version it carries, so " +
        "this run cannot be attested. Check out a complete certcrypt-conformance.",
    );
  }
  const raw = readFileSync(versionPath, "utf-8").trim();
  if (!raw) {
    throw new Error(`conformance VERSION at ${versionPath} is empty`);
  }
  return raw;
}

const VECTORS_VERSION = readVectorsVersion();
console.log(`Conformance vectors: ${VECTORS_VERSION} (${FIXTURES_BASE})\n`);

let passed = 0;
let failed = 0;
const failures: string[] = [];

for (const baseDir of FIXTURE_DIRS) {
  // A missing fixture directory is a BROKEN CONTRACT, never an empty one. Skipping
  // it silently would report "15 passed, 0 failed" for a checkout carrying only
  // `conformance/`, and then record an attestation naming a contract version whose
  // adversarial vectors never ran — the precise claim CONFORMANCE_VECTORS_VERSION
  // exists to keep honest. Fail instead, naming what is absent.
  if (!existsSync(baseDir)) {
    throw new Error(
      `conformance fixture directory missing: ${baseDir}. The contract is ` +
        `incomplete, so no attestation can be made from this checkout. Check out ` +
        `certcrypt-conformance at a complete revision, or point ` +
        `CERTCRYPT_CONFORMANCE_DIR at one.`,
    );
  }

  const entries = readdirSync(baseDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .sort((a, b) => a.name.localeCompare(b.name));

  for (const entry of entries) {
    const fixtureDir = join(baseDir, entry.name);
    const inputPath = join(fixtureDir, "input.json");
    const expectedPath = join(fixtureDir, "expected-result.json");

    if (!existsSync(inputPath) || !existsSync(expectedPath)) continue;

    const rawRequest: VerifierRequest = JSON.parse(
      readFileSync(inputPath, "utf-8")
    );
    // Resolve relative paths in the request against the fixture directory
    const request = resolveRequestPaths(rawRequest, fixtureDir);
    const expected = JSON.parse(readFileSync(expectedPath, "utf-8"));

    let actual;
    try {
      actual = verify(request, conformanceConfig);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      failed++;
      failures.push(`${entry.name}: EXCEPTION — ${msg}`);
      continue;
    }

    let fixturePassed = true;

    // Check result_code
    if (actual.result_code !== expected.result_code) {
      fixturePassed = false;
      failures.push(
        `${entry.name}: result_code expected=${expected.result_code} got=${actual.result_code}`
      );
    }

    // Check verification_target: the contract pins the target the verifier
    // resolved, so a verifier cannot reach the right code on the wrong route.
    if (actual.verification_target !== expected.verification_target) {
      fixturePassed = false;
      failures.push(
        `${entry.name}: verification_target expected=${expected.verification_target} got=${actual.verification_target}`
      );
    }

    // Check failed_check_ids: the SAME set, nothing missing and nothing extra.
    // Order is not part of the contract; membership is.
    const expectedIds = [...new Set((expected.failed_check_ids ?? []) as string[])].sort();
    const actualIds = [...new Set(actual.failed_check_ids)].sort();
    if (JSON.stringify(expectedIds) !== JSON.stringify(actualIds)) {
      fixturePassed = false;
      failures.push(
        `${entry.name}: failed_check_ids expected=${JSON.stringify(expectedIds)} got=${JSON.stringify(actualIds)}`
      );
    }

    // Check certcrypt_lineage booleans (if specified in expected)
    if (expected.certcrypt_lineage && actual.certcrypt_lineage) {
      const el = expected.certcrypt_lineage as unknown as Record<string, unknown>;
      const al = actual.certcrypt_lineage as unknown as Record<string, unknown>;
      for (const key of Object.keys(el)) {
        if (typeof el[key] === "boolean" && al[key] !== el[key]) {
          fixturePassed = false;
          failures.push(
            `${entry.name}: certcrypt_lineage.${key} expected=${el[key]} got=${al[key]}`
          );
        }
      }
    }

    // Check additional_verifications (opt-in, field by field): a fixture may pin
    // the ML-DSA-65 component's separately surfaced outcome. Only the fields the
    // fixture declares are compared — Q001/Q003 pin performed/algorithm/passed and
    // leave `reason` free, since its wording is implementation-specific.
    const expectedAv = (expected as unknown as Record<string, unknown>).additional_verifications as
      | Record<string, Record<string, unknown>>
      | undefined;
    if (expectedAv && typeof expectedAv === "object") {
      const actualAv = (actual.additional_verifications ?? {}) as unknown as Record<
        string,
        Record<string, unknown> | undefined
      >;
      for (const [slot, fields] of Object.entries(expectedAv)) {
        for (const [field, value] of Object.entries(fields)) {
          const got = actualAv[slot]?.[field];
          if (got !== value) {
            fixturePassed = false;
            failures.push(
              `${entry.name}: additional_verifications.${slot}.${field} expected=${JSON.stringify(value)} got=${JSON.stringify(got)}`
            );
          }
        }
      }
    }

    // Check the attested node (opt-in): a fixture that declares `attested_node`
    // (an object, or null) pins it exactly.
    if ("attested_node" in (expected as object)) {
      const want = JSON.stringify((expected as Record<string, unknown>).attested_node);
      const got = JSON.stringify(actual.attested_node);
      if (want !== got) {
        fixturePassed = false;
        failures.push(`${entry.name}: attested_node expected=${want} got=${got}`);
      }
    }

    // Check the per-subject scope (opt-in): a fixture that declares
    // `subject_scope` pins it exactly — which subjects are opaque inputs and
    // which are declared collections.
    if ("subject_scope" in (expected as object)) {
      const want = JSON.stringify((expected as Record<string, unknown>).subject_scope);
      const got = JSON.stringify(actual.subject_scope);
      if (want !== got) {
        fixturePassed = false;
        failures.push(`${entry.name}: subject_scope expected=${want} got=${got}`);
      }
    }

    // Check the missing artifacts (opt-in): a fixture that declares
    // `required_artifacts_missing` pins the same set, nothing missing and
    // nothing extra; order is not compared.
    if ("required_artifacts_missing" in (expected as object)) {
      const want = JSON.stringify(
        [...new Set((expected as Record<string, unknown>).required_artifacts_missing as string[])].sort()
      );
      const got = JSON.stringify([...new Set(actual.required_artifacts_missing ?? [])].sort());
      if (want !== got) {
        fixturePassed = false;
        failures.push(`${entry.name}: required_artifacts_missing expected=${want} got=${got}`);
      }
    }

    // Check top-level boolean assertions a fixture may pin (opt-in): e.g.
    // production_verification, complete_verification_against_original_material_*.
    // Only compared when the fixture's expected explicitly declares them, so
    // fixtures that don't care are unaffected.
    const TOP_LEVEL_BOOL_ASSERTIONS = [
      "production_verification",
      "complete_verification_against_original_material_performed",
      "complete_verification_against_original_material_passed",
    ] as const;
    const ex = expected as unknown as Record<string, unknown>;
    const ac = actual as unknown as Record<string, unknown>;
    for (const key of TOP_LEVEL_BOOL_ASSERTIONS) {
      if (typeof ex[key] === "boolean" && ac[key] !== ex[key]) {
        fixturePassed = false;
        failures.push(`${entry.name}: ${key} expected=${ex[key]} got=${ac[key]}`);
      }
    }

    if (fixturePassed) {
      passed++;
      console.log(`  PASS  ${entry.name}`);
    } else {
      failed++;
      console.log(`  FAIL  ${entry.name}`);
    }
  }
}

console.log(`\n${passed} passed, ${failed} failed`);

if (failures.length > 0) {
  console.log("\nFailure details:");
  for (const f of failures) {
    console.log(`  - ${f}`);
  }
}

/**
 * Record — or retract — the conformance attestation in the BUILD OUTPUT.
 *
 * Written to `dist/core/conformance/attestation.js` (and its `.d.ts`), the
 * artifact a consumer actually imports. It is deliberately NOT written back to
 * the committed `core/conformance/attestation.ts`: a version in source is a
 * string someone can edit, and would survive in a checkout that later stops
 * passing. In the build output it is a fact about THIS build, produced by the
 * run that did the work.
 *
 * On failure the attestation is reset to `null` rather than left untouched. A
 * build that passed yesterday and fails today must not keep yesterday's claim:
 * silence is correct, a stale version is a lie.
 */
function writeAttestation(version: string | null, fixturesPassed: number | null): void {
  const outDir = join(TOOLKIT_ROOT, "dist", "core", "conformance");
  if (!existsSync(outDir)) {
    // Not built (running from source via a loader) — nothing to attest into.
    // Not an error: the suite's verdict stands on its own.
    return;
  }
  const lit = version === null ? "null" : JSON.stringify(version);
  const count = fixturesPassed === null ? "null" : String(fixturesPassed);
  const banner =
    "// GENERATED by scripts/run-conformance.ts — do not edit.\n" +
    "// Written by the run that executed the vectors; absent that run, null.\n";
  writeFileSync(
    join(outDir, "attestation.js"),
    `${banner}export const CONFORMANCE_VECTORS_VERSION = ${lit};\n` +
      `export const CONFORMANCE_FIXTURES_PASSED = ${count};\n`,
    "utf-8",
  );
  writeFileSync(
    join(outDir, "attestation.d.ts"),
    `${banner}export declare const CONFORMANCE_VECTORS_VERSION: string | null;\n` +
      `export declare const CONFORMANCE_FIXTURES_PASSED: number | null;\n`,
    "utf-8",
  );
}

if (failed > 0) {
  writeAttestation(null, null);
  console.log(
    "\nConformance attestation CLEARED (suite failed): " +
      "CONFORMANCE_VECTORS_VERSION = null",
  );
} else {
  writeAttestation(VECTORS_VERSION, passed);
  console.log(
    `\nConformance attestation recorded: ` +
      `CONFORMANCE_VECTORS_VERSION = "${VECTORS_VERSION}" (${passed} fixtures)`,
  );
}

process.exit(failed > 0 ? 1 : 0);

/**
 * Resolve relative paths in a request against a fixture directory.
 * Absolute paths pass through unchanged.
 */
function resolveRequestPaths(
  request: VerifierRequest,
  fixtureDir: string
): VerifierRequest {
  const r = { ...request };
  const resolvePath = (p: string | undefined): string | undefined => {
    if (!p) return p;
    return isAbsolute(p) ? p : resolve(fixtureDir, p);
  };
  if (r.base_certificate_path)
    r.base_certificate_path = resolvePath(r.base_certificate_path)!;
  if (r.independence_proof_path)
    r.independence_proof_path = resolvePath(r.independence_proof_path);
  if (r.settlement_material_path)
    r.settlement_material_path = resolvePath(r.settlement_material_path);
  if (r.system_foundation_path)
    r.system_foundation_path = resolvePath(r.system_foundation_path);
  if (r.capacity_evidence_path)
    r.capacity_evidence_path = resolvePath(r.capacity_evidence_path);
  if (r.commitment_inclusion_proof_path)
    r.commitment_inclusion_proof_path = resolvePath(
      r.commitment_inclusion_proof_path,
    );
  if (r.verification_package_path)
    r.verification_package_path = resolvePath(r.verification_package_path);
  if (r.original_material_path)
    r.original_material_path = resolvePath(r.original_material_path);
  return r;
}
