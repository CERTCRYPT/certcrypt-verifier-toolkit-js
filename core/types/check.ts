  AGGREGATED_INTERPRETATION_UNIQUE: "INDEPENDENT_INVALID" | "INCOMPLETE";
  ISSUANCE_PARTICIPATION_VALID: "INDEPENDENT_INVALID";
  PROOF_SIGNATURE_VALID: "INCOMPLETE" | "UNSUPPORTED" | "REJECTED" | "INDEPENDENT_INVALID";
