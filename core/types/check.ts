  RULES_DOMAIN_EXACT: "REJECTED" | "UNSUPPORTED";
  RULES_CORPUS_COMMITMENT_PRESENT: "REJECTED";
  SYSTEM_DOMAIN_EXACT: "INDEPENDENT_INVALID";
  SYSTEM_ROOT_BINDING_VALID: "INDEPENDENT_INVALID";
  LEAF_BINDING_VALID: "INDEPENDENT_INVALID" | "INCOMPLETE" | "REJECTED";
  SETTLEMENT_REF_VALID: "INDEPENDENT_INVALID" | "INCOMPLETE" | "REJECTED";
